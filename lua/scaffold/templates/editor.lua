-- Editor- and toolchain-facing hints written next to a generated project.
--
-- Why this exists: a fresh C/C++ project has no compile_commands.json until
-- the first build, so clangd used to guess (default flags, wrong include dirs,
-- and .h files parsed as C). These files make the standard and include paths
-- explicit from the very first :edit.

local M = {}

--- `compile_flags.txt`: clangd's fallback database, used until the real
--- `compile_commands.json` exists. Relative paths are resolved from the
--- directory containing the file (the project root), not from the source file.
---@param standard string e.g. "c++23" or "c23"
---@param includes? string[] directories relative to the project root
---@return string
function M.compile_flags(standard, includes)
  local lines = {
    "-std=" .. standard,
    "-Wall",
    "-Wextra",
  }
  for _, dir in ipairs(includes or {}) do
    lines[#lines + 1] = "-I" .. dir
  end
  return table.concat(lines, "\n") .. "\n"
end

--- `.clangd`: clangd picks the language from the extension and assumes C++ for
--- `.h`, which breaks C projects (and C++ headers need header mode). Force the
--- header language explicitly.
---@param standard string e.g. "c++23"
---@param mode? string "c++-header" (default) or "c-header"
---@return string
function M.clangd(standard, mode)
  return table.concat({
    "# Generated by Scaffold.nvim.",
    "# Flags come from compile_flags.txt before the first build and from",
    "# build/compile_commands.json afterwards.",
    "---",
    "If:",
    "  PathMatch: " .. [[.*\.(h|hh|hpp|hxx)$]],
    "CompileFlags:",
    "  Add:",
    "    - -x" .. (mode or "c++-header"),
    "    - -std=" .. standard,
    "",
  }, "\n")
end

--- `.clang-format`: project-local formatting style, so a clone formats the
--- same way everywhere without depending on the developer's home directory.
---
--- Uses the user's `~/.clang-format` when it exists (generated projects then
--- match the editor setup), otherwise a prettier-like default: 4-space indent,
--- attached braces, no column limit.
---@return string
function M.clang_format()
  local home = vim.fn.expand("~")
  local user = home ~= "" and vim.fs.joinpath(home, ".clang-format") or nil
  if user and vim.fn.filereadable(user) == 1 then
    local ok, lines = pcall(vim.fn.readfile, user)
    if ok and type(lines) == "table" and #lines > 0 then
      return table.concat(lines, "\n") .. "\n"
    end
  end

  return table.concat({
    "---",
    "# Generated by Scaffold.nvim (prettier-like: 4-space, no column limit).",
    "BasedOnStyle: LLVM",
    "Language: Cpp",
    "IndentWidth: 4",
    "TabWidth: 4",
    "UseTab: Never",
    "ColumnLimit: 0",
    "ReflowComments: false",
    "BreakStringLiterals: false",
    "BreakBeforeBraces: Attach",
    "AllowShortFunctionsOnASingleLine: None",
    "AllowShortIfStatementsOnASingleLine: WithoutElse",
    "AllowShortLoopsOnASingleLine: true",
    "AllowShortBlocksOnASingleLine: Empty",
    "ConstructorInitializerIndentWidth: 4",
    "PointerAlignment: Left",
    "ReferenceAlignment: Left",
    "SortIncludes: Never",
    "IncludeBlocks: Preserve",
    "IndentCaseLabels: true",
    "SpaceBeforeParens: ControlStatements",
    "",
  }, "\n")
end

return M
